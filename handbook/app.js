  /* ---------- step player ---------- */
  function player({ code, frames, input }) {
    const root = h("div", { class: "player" + (code ? "" : " solo") });
    const stage = h("div", { class: "stage" });
    if (input) stage.appendChild(h("div", { class: "vin" }, "<b>Input:</b> " + esc(input)));
    const msg = h("div", { class: "msg", "aria-live": "polite" });
    const views = h("div", { class: "views" });
    const ctrl = h("div", { class: "ctrl" });
    ctrl.innerHTML = `<button data-a="first" aria-label="First step">⏮</button><button data-a="prev" aria-label="Previous step">◀</button><button class="play" data-a="play" aria-label="Play">▶</button><button data-a="next" aria-label="Next step">▶|</button><button data-a="last" aria-label="Last step">⏭</button><input type="range" min="0" value="0" aria-label="Step"><select aria-label="Speed"><option value="1800">0.5×</option><option value="1100" selected>1×</option><option value="600">2×</option></select><span class="cnt"></span>`;
    stage.append(msg, views, ctrl);
    root.appendChild(stage);
    let pre = null;
    if (code) { pre = codeBlock(code); root.appendChild(pre); }
    const range = ctrl.querySelector("input"), cnt = ctrl.querySelector(".cnt"), playBtn = ctrl.querySelector(".play"), speed = ctrl.querySelector("select");
    range.max = Math.max(0, frames.length - 1);
    let i = 0, timer = null;
    function show(k) {
      i = Math.max(0, Math.min(frames.length - 1, k));
      const f = frames[i];
      if (!f) { msg.textContent = "No steps recorded."; return; }
      msg.textContent = f.m;
      msg.classList.toggle("done", f.l === -1 && f.m.startsWith("Result:"));
      views.replaceChildren(...f.v.map(renderView));
      range.value = i;
      cnt.textContent = `${i + 1} / ${frames.length}`;
      if (pre) {
        pre.querySelectorAll(".cur").forEach((e) => e.classList.remove("cur"));
        const ln = pre.children[f.l];
        if (ln) { ln.classList.add("cur"); const top = ln.offsetTop - pre.clientHeight / 2; if (pre.scrollHeight > pre.clientHeight) pre.scrollTop = top; }
      }
    }
    function stop() { clearInterval(timer); timer = null; playBtn.textContent = "▶"; playBtn.setAttribute("aria-label", "Play"); }
    function play() {
      if (i >= frames.length - 1) show(0);
      playBtn.textContent = "⏸"; playBtn.setAttribute("aria-label", "Pause");
      timer = setInterval(() => { if (i >= frames.length - 1) stop(); else show(i + 1); }, +speed.value);
    }
    ctrl.addEventListener("click", (e) => {
      const a = e.target.closest("button")?.dataset.a; if (!a) return;
      if (a === "play") return timer ? stop() : play();
      stop();
      show({ first: 0, prev: i - 1, next: i + 1, last: frames.length - 1 }[a]);
    });
    range.addEventListener("input", () => { stop(); show(+range.value); });
    speed.addEventListener("change", () => { if (timer) { stop(); play(); } });
    root.tabIndex = 0;
    root.addEventListener("keydown", (e) => {
      if (e.target.tagName === "SELECT" || e.target.tagName === "INPUT") return;
      if (e.key === "ArrowRight") { stop(); show(i + 1); e.preventDefault(); }
      if (e.key === "ArrowLeft") { stop(); show(i - 1); e.preventDefault(); }
      if (e.key === " ") { timer ? stop() : play(); e.preventDefault(); }
    });
    root._stop = stop;
    show(0);
    return root;
  }

  /* ---------- search ---------- */
  const ALL = [];
  TOPICS.forEach((t) => t.qs.forEach((q) => ALL.push({ t, q, hay: [q.title, q.tags, q.diff, t.title, "lc " + q.lc, String(q.lc)].join(" ").toLowerCase() })));
  const qIn = document.getElementById("q"), resBox = document.getElementById("results");
  let sel = 0, hits = [];
  function search(text) {
    const words = text.toLowerCase().trim().split(/\s+/).filter(Boolean);
    if (!words.length) return [];
    const topicHits = TOPICS.filter((t) => words.every((w) => (t.title + " " + t.blurb).toLowerCase().includes(w))).map((t) => ({ topic: t }));
    const qs = ALL.filter((x) => words.every((w) => x.hay.includes(w)))
      .sort((a, b) => (b.q.title.toLowerCase().startsWith(words[0]) - a.q.title.toLowerCase().startsWith(words[0])));
    return topicHits.concat(qs).slice(0, 14);
  }
  function drawResults() {
    if (!qIn.value.trim()) { resBox.hidden = true; return; }
    resBox.hidden = false;
    if (!hits.length) { resBox.innerHTML = `<div class="empty">No match for “${esc(qIn.value)}”. Try a pattern like “sliding window”, a LeetCode number, or a title.</div>`; return; }
    resBox.innerHTML = hits.map((x, k) => x.topic
      ? `<a href="#/t/${x.topic.id}" class="${k === sel ? "on" : ""}"><span class="rt">${esc(x.topic.title)}</span><span class="diff Easy">Topic</span><span class="rs">${x.topic.qs.length} questions · ${esc(x.topic.blurb)}</span></a>`
      : `<a href="#/q/${x.t.id}/${x.q.id}" class="${k === sel ? "on" : ""}"><span class="rt">${esc(x.q.title)}</span><span class="diff ${x.q.diff}">${x.q.diff}</span><span class="rs">${esc(x.t.title)} · LC ${x.q.lc} · ${esc(x.q.tags)}</span></a>`).join("");
  }
  qIn.addEventListener("input", () => { hits = search(qIn.value); sel = 0; drawResults(); });
  qIn.addEventListener("keydown", (e) => {
    if (e.key === "ArrowDown") { sel = Math.min(hits.length - 1, sel + 1); drawResults(); e.preventDefault(); }
    else if (e.key === "ArrowUp") { sel = Math.max(0, sel - 1); drawResults(); e.preventDefault(); }
    else if (e.key === "Enter" && hits[sel]) { location.hash = resBox.querySelectorAll("a")[sel].getAttribute("href"); closeSearch(); }
    else if (e.key === "Escape") closeSearch();
  });
  function closeSearch() { resBox.hidden = true; qIn.blur(); }
  resBox.addEventListener("click", (e) => { if (e.target.closest("a")) { qIn.value = ""; resBox.hidden = true; } });
  document.addEventListener("click", (e) => { if (!e.target.closest(".search")) resBox.hidden = true; });
